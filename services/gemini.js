/**
 * services/gemini.js
 * Client for Google Gemini API (v1beta).
 * Supports streaming text, multimodal vision, automatic model fallback, and robust error recovery.
 */

const GEMINI_BASE_URL = 'https://generativelanguage.googleapis.com/v1beta';
const FALLBACK_MODELS = [
  'gemini-2.5-flash',
  'gemini-2.0-flash',
  'gemini-2.5-flash-lite'
];

export class GeminiClient {
  constructor(apiKey, model = 'gemini-2.5-flash') {
    this.apiKey = apiKey;
    this.model = model || 'gemini-2.5-flash';
  }

  setApiKey(key) {
    this.apiKey = key;
  }

  setModel(model) {
    this.model = model;
  }

  /**
   * Automatically falls back to supported Gemini 2.x/2.5 models if the chosen model returns 404 (retired).
   */
  async _executeWithModelFallback(requestFn) {
    const candidateModels = [
      this.model,
      ...FALLBACK_MODELS.filter(m => m !== this.model)
    ].filter((m, idx, arr) => Boolean(m) && arr.indexOf(m) === idx);

    let lastError = null;

    for (const modelToTry of candidateModels) {
      try {
        const result = await requestFn(modelToTry);
        if (this.model !== modelToTry) {
          console.info(`[Snip] Auto-switched to active model: ${modelToTry}`);
          this.model = modelToTry;
          // Asynchronously update local storage with the working model
          if (typeof chrome !== 'undefined' && chrome.storage && chrome.storage.local) {
            chrome.storage.local.set({ selectedModel: modelToTry });
          }
        }
        return result;
      } catch (err) {
        lastError = err;
        const msg = (err.message || '').toLowerCase();
        // If 404 model not found, try next candidate
        if (msg.includes('404') && (msg.includes('not found') || msg.includes('not supported'))) {
          console.warn(`[Snip] Model "${modelToTry}" not found. Trying next available model...`);
          continue;
        }
        throw err;
      }
    }

    throw lastError;
  }

  /**
   * Helper to execute fetch with exponential backoff on HTTP 429 rate limits.
   */
  async _fetchWithRetry(url, options, maxRetries = 3) {
    let delay = 1500;
    for (let attempt = 0; attempt <= maxRetries; attempt++) {
      try {
        const response = await fetch(url, options);

        if (response.status === 429) {
          if (attempt === maxRetries) {
            throw new Error(`Gemini API rate limit reached (HTTP 429). Please wait a moment or switch models.`);
          }
          console.warn(`[Snip] Gemini 429 Rate limit. Backing off for ${delay}ms...`);
          await new Promise(resolve => setTimeout(resolve, delay));
          delay *= 2;
          continue;
        }

        if (!response.ok) {
          const errBody = await response.text();
          let message = `Gemini API error (HTTP ${response.status})`;
          try {
            const parsed = JSON.parse(errBody);
            if (parsed.error && parsed.error.message) {
              message += `: ${parsed.error.message}`;
            }
          } catch (_) {
            message += `: ${errBody}`;
          }
          throw new Error(message);
        }

        return response;
      } catch (err) {
        if (attempt === maxRetries || err.message.includes('API error (HTTP 400)') || err.message.includes('API error (HTTP 403)') || err.message.includes('API error (HTTP 404)')) {
          throw err;
        }
        await new Promise(resolve => setTimeout(resolve, delay));
        delay *= 2;
      }
    }
  }

  /**
   * Generates regular non-streaming content.
   */
  async generateContent(prompt, systemInstruction = null) {
    if (!this.apiKey) {
      throw new Error('Gemini API Key is not configured. Please add your key in Extension Settings.');
    }

    return await this._executeWithModelFallback(async (activeModel) => {
      const endpoint = `${GEMINI_BASE_URL}/models/${activeModel}:generateContent?key=${this.apiKey}`;
      const payload = {
        contents: [{ role: 'user', parts: [{ text: prompt }] }],
        generationConfig: {
          temperature: 0.2,
          topP: 0.95,
          maxOutputTokens: 2048
        }
      };

      if (systemInstruction) {
        payload.systemInstruction = {
          parts: [{ text: systemInstruction }]
        };
      }

      const res = await this._fetchWithRetry(endpoint, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify(payload)
      });

      const data = await res.json();
      const candidate = data.candidates && data.candidates[0];
      if (!candidate || !candidate.content || !candidate.content.parts) {
        throw new Error('No response generated by Gemini model.');
      }

      return candidate.content.parts.map(p => p.text).join('');
    });
  }

  /**
   * Streams content via Server-Sent Events (SSE).
   * @param {string} prompt
   * @param {string|null} systemInstruction
   * @param {function(string, boolean): void} onChunk - callback(textChunk, isDone)
   */
  async streamGenerateContent(prompt, systemInstruction = null, onChunk) {
    if (!this.apiKey) {
      throw new Error('Gemini API Key is not configured. Please add your key in Extension Settings.');
    }

    return await this._executeWithModelFallback(async (activeModel) => {
      const endpoint = `${GEMINI_BASE_URL}/models/${activeModel}:streamGenerateContent?alt=sse&key=${this.apiKey}`;
      const payload = {
        contents: [{ role: 'user', parts: [{ text: prompt }] }],
        generationConfig: {
          temperature: 0.3,
          topP: 0.95,
          maxOutputTokens: 4096
        }
      };

      if (systemInstruction) {
        payload.systemInstruction = {
          parts: [{ text: systemInstruction }]
        };
      }

      const response = await this._fetchWithRetry(endpoint, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify(payload)
      });

      const reader = response.body.getReader();
      const decoder = new TextDecoder('utf-8');
      let buffer = '';

      try {
        while (true) {
          const { value, done } = await reader.read();
          if (done) break;

          buffer += decoder.decode(value, { stream: true });
          const lines = buffer.split('\n');
          buffer = lines.pop(); // keep partial line in buffer

          for (const line of lines) {
            const trimmed = line.trim();
            if (trimmed.startsWith('data: ')) {
              const jsonStr = trimmed.slice(6);
              if (jsonStr === '[DONE]') continue;
              try {
                const data = JSON.parse(jsonStr);
                const partText = data.candidates?.[0]?.content?.parts?.[0]?.text;
                if (partText && onChunk) {
                  onChunk(partText, false);
                }
              } catch (_) {
                // Ignore partial JSON parse chunks
              }
            }
          }
        }
        if (onChunk) onChunk('', true);
      } catch (streamErr) {
        console.error('[Snip] Streaming error:', streamErr);
        throw streamErr;
      }
    });
  }

  /**
   * Multi-turn chat generation with history.
   */
  async chatWithHistory(messages, systemInstruction = null, onChunk = null) {
    if (!this.apiKey) {
      throw new Error('Gemini API Key is not configured. Please add your key in Extension Settings.');
    }

    // Convert messages array: [{ role: 'user'|'model', content: string }]
    const contents = messages.map(m => ({
      role: m.role === 'model' || m.role === 'assistant' ? 'model' : 'user',
      parts: [{ text: m.content }]
    }));

    return await this._executeWithModelFallback(async (activeModel) => {
      if (onChunk) {
        const endpoint = `${GEMINI_BASE_URL}/models/${activeModel}:streamGenerateContent?alt=sse&key=${this.apiKey}`;
        const payload = {
          contents,
          generationConfig: { temperature: 0.3, maxOutputTokens: 2048 }
        };
        if (systemInstruction) {
          payload.systemInstruction = { parts: [{ text: systemInstruction }] };
        }

        const response = await this._fetchWithRetry(endpoint, {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify(payload)
        });

        const reader = response.body.getReader();
        const decoder = new TextDecoder('utf-8');
        let buffer = '';

        while (true) {
          const { value, done } = await reader.read();
          if (done) break;
          buffer += decoder.decode(value, { stream: true });
          const lines = buffer.split('\n');
          buffer = lines.pop();
          for (const line of lines) {
            const trimmed = line.trim();
            if (trimmed.startsWith('data: ')) {
              try {
                const data = JSON.parse(trimmed.slice(6));
                const partText = data.candidates?.[0]?.content?.parts?.[0]?.text;
                if (partText) onChunk(partText, false);
              } catch (_) {}
            }
          }
        }
        onChunk('', true);
        return;
      }

      // Non-streaming fallback
      const endpoint = `${GEMINI_BASE_URL}/models/${activeModel}:generateContent?key=${this.apiKey}`;
      const payload = {
        contents,
        generationConfig: { temperature: 0.3, maxOutputTokens: 2048 }
      };
      if (systemInstruction) {
        payload.systemInstruction = { parts: [{ text: systemInstruction }] };
      }

      const res = await this._fetchWithRetry(endpoint, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify(payload)
      });

      const data = await res.json();
      return data.candidates?.[0]?.content?.parts?.map(p => p.text).join('') || '';
    });
  }

  /**
   * Multimodal vision query on a base64 image screenshot.
   */
  async askVision(base64DataUrl, questionText, onChunk = null) {
    if (!this.apiKey) {
      throw new Error('Gemini API Key is not configured. Please add your key in Extension Settings.');
    }

    let mimeType = 'image/png';
    let base64Data = base64DataUrl;
    if (base64DataUrl.includes(',')) {
      const match = base64DataUrl.match(/data:([^;]+);base64,(.*)$/);
      if (match) {
        mimeType = match[1];
        base64Data = match[2];
      }
    }

    const payload = {
      contents: [{
        role: 'user',
        parts: [
          { text: questionText || 'Describe what you see on this screen and answer any visible questions.' },
          {
            inlineData: {
              mimeType: mimeType,
              data: base64Data
            }
          }
        ]
      }],
      generationConfig: {
        temperature: 0.2,
        maxOutputTokens: 2048
      }
    };

    return await this._executeWithModelFallback(async (activeModel) => {
      if (onChunk) {
        const endpoint = `${GEMINI_BASE_URL}/models/${activeModel}:streamGenerateContent?alt=sse&key=${this.apiKey}`;
        const response = await this._fetchWithRetry(endpoint, {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify(payload)
        });

        const reader = response.body.getReader();
        const decoder = new TextDecoder('utf-8');
        let buffer = '';

        while (true) {
          const { value, done } = await reader.read();
          if (done) break;
          buffer += decoder.decode(value, { stream: true });
          const lines = buffer.split('\n');
          buffer = lines.pop();
          for (const line of lines) {
            const trimmed = line.trim();
            if (trimmed.startsWith('data: ')) {
              try {
                const data = JSON.parse(trimmed.slice(6));
                const partText = data.candidates?.[0]?.content?.parts?.[0]?.text;
                if (partText) onChunk(partText, false);
              } catch (_) {}
            }
          }
        }
        onChunk('', true);
        return;
      }

      const endpoint = `${GEMINI_BASE_URL}/models/${activeModel}:generateContent?key=${this.apiKey}`;
      const res = await this._fetchWithRetry(endpoint, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify(payload)
      });

      const data = await res.json();
      return data.candidates?.[0]?.content?.parts?.map(p => p.text).join('') || '';
    });
  }

  /**
   * Fetches list of models supported by the provided API key.
   */
  async listAvailableModels() {
    if (!this.apiKey) return [];
    try {
      const res = await fetch(`${GEMINI_BASE_URL}/models?key=${this.apiKey}`);
      if (!res.ok) return [];
      const data = await res.json();
      return (data.models || [])
        .filter(m => m.supportedGenerationMethods && m.supportedGenerationMethods.includes('generateContent'))
        .map(m => m.name.replace('models/', ''));
    } catch (_) {
      return [];
    }
  }
}
